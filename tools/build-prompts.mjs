// Regenerates assets/higgsfield/PROMPTS.md from assets/higgsfield/manifest.json.
// Usage: node tools/build-prompts.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const dir = join(dirname(fileURLToPath(import.meta.url)), '..', 'assets', 'higgsfield');
const manifest = JSON.parse(readFileSync(join(dir, 'manifest.json'), 'utf8'));

const titles = {
  concept: '1. Tuk-tuk concept / reference renders',
  texture: '2. Seamless PBR texture sets',
  environment: '3. 360° sky / environment map',
  plate: '4. Background and skyline plates',
  loop: '5. Optional loops'
};

let out = `# Higgsfield prompts

Art direction: **${manifest.artDirection}**.

The Higgsfield connector available to Claude Code is read-only (workspaces, balance,
model catalogue, existing generations), so these assets have to be generated by hand
in the Higgsfield app. Paste each prompt, pick the listed model / resolution / aspect,
save the result to the listed path under \`assets/higgsfield/\`, then flip that asset's
\`status\` to \`"ready"\` in \`manifest.json\`. Until then the game uses procedural
placeholders.

For texture sets only the albedo is required. If you also produce normal / roughness /
AO maps (for example by running the albedo through a material tool), save them at the
listed paths; otherwise the game derives them from the albedo when it loads.

This file is generated: edit \`manifest.json\` and run \`node tools/build-prompts.mjs\`.
`;

for (const kind of Object.keys(titles)) {
  const items = manifest.assets.filter((a) => a.kind === kind);
  if (!items.length) continue;
  out += `\n## ${titles[kind]}\n`;
  for (const a of items) {
    out += `\n### ${a.id}${a.optional ? ' (optional)' : ''}\n\n`;
    out += `- Save as: \`assets/higgsfield/${a.file}\`\n`;
    for (const k of ['normal', 'roughness', 'ao']) {
      if (a[k]) out += `- Optional ${k} map: \`assets/higgsfield/${a[k]}\`\n`;
    }
    out += `- Model: \`${a.model}\`, resolution ${a.resolution}, aspect ${a.aspect}\n`;
    if (a.postProcess) out += `- After generating: ${a.postProcess}\n`;
    out += `- Status: ${a.status}\n\n`;
    out += '```text\n' + a.prompt + '\n```\n';
  }
}

writeFileSync(join(dir, 'PROMPTS.md'), out);
console.log(`Wrote PROMPTS.md with ${manifest.assets.length} prompts`);
