// Bundles src/boot.js + src/gfx + the vendored Three.js into one classic script,
// dist/tuktuk.js. A classic <script> loads from file:// (double-clicking index.html),
// where browsers block ES modules.
//
// Usage: npm run build        (one-off)
//        npm run watch        (rebuild on every change under src/)
import * as esbuild from 'esbuild';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const vendor = join(root, 'vendor', 'three');

// 'three' -> vendored build, 'three/addons/x' -> vendored addons (same mapping as the old import map)
const vendoredThree = {
  name: 'vendored-three',
  setup(build) {
    build.onResolve({ filter: /^three$/ }, () => ({ path: join(vendor, 'three.module.min.js') }));
    build.onResolve({ filter: /^three\/addons\// }, (args) => ({
      path: join(vendor, 'addons', args.path.slice('three/addons/'.length))
    }));
  }
};

const options = {
  entryPoints: [join(root, 'src', 'boot.js')],
  outfile: join(root, 'dist', 'tuktuk.js'),
  bundle: true,
  format: 'iife',
  target: ['es2020'],
  minify: true,
  legalComments: 'eof',
  banner: { js: '/* Tuk-Tuk Basha graphics bundle. Generated by tools/build.mjs from src/ - do not edit. Three.js (c) three.js authors, MIT. */' },
  plugins: [vendoredThree],
  logLevel: 'info'
};

if (process.argv.includes('--watch')) {
  const ctx = await esbuild.context(options);
  await ctx.watch();
  console.log('Watching src/ for changes...');
} else {
  await esbuild.build(options);
}
